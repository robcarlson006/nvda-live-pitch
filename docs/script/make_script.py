"""Write the readable pitch script from the slides.

    python3 docs/script/make_script.py            → docs/script/pitch-script-v10.md

Everything comes from docs/script/spine.yaml (the teleprompter): each slide's spoken line (`say`), then what builds on
screen (▸) and the phrase that triggers it. Figures are looked up from data/clean, exactly as the stage shows them.
Re-run after any script or data change; never edit the .md by hand.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "fallback"))
from build import resolve  # noqa: E402  the backup deck's own lookup, so both read the data the same way

PARTS = {
    "founding": "Part one: Story (Rob)",
    "last-quarter": "Part two: Numbers (Panshul)",
    "already-doing": "Part three: Future (Mi'kael)",
    "governance": "Part four: Responsibility (Mi'kael)",
    "recommendation": "Part five: Verdict (Mi'kael, then Rob)",
}


def spoken(text: str) -> str:
    return re.sub(r"\*+", "", resolve(text))


def main() -> None:
    slides = yaml.safe_load((ROOT / "docs/script/spine.yaml").read_text())
    words = {}
    out = [
        "# The pitch script, draft 10 (generated from the slides)",
        "",
        "Generated by `docs/script/make_script.py` from `docs/script/spine.yaml`, so it matches the slides exactly. "
        "Plain paragraphs are spoken. Lines starting with ▸ build on screen (the trigger phrase is in quotes); 🔍 is a "
        "zoom into the chart; ⏱ an element that builds on its own. Figures are the live data values.",
        "",
        "Cut to nine minutes on 25 Nov (cut slides are in the Q&A bank). See the word counts at the end.",
    ]
    for s in slides:
        if s["id"] in PARTS:
            out += ["", "---", "", f"## {PARTS[s['id']]}"]
        say = spoken(s.get("say", ""))
        # Same rule as app/scripts/measure-script.ts: a spoken figure ("three hundred and eighty-nine dollars") is ~5 words.
        raw = s.get("say", "")
        figures = len(re.findall(r"\{\{[^}]*\}\}", raw))
        plain = re.sub(r"\{\{[^}]*\}\}", " ", raw).replace("*", "").replace("_", "")
        words[s["speaker"]] = words.get(s["speaker"], 0) + sum(1 for w in plain.split() if re.search(r"[A-Za-z0-9]", w)) + 5 * figures
        opt = " (optional)" if s.get("optional") else ""
        out += ["", f"### {s['id']}{opt}: {resolve(s['title'])}", f"*{s['speaker']} · starts on “{s['cues'][0]}”*", "", say, ""]
        if s.get("stat"):
            st = s["stat"]
            from build import value
            out.append(f"▸ Big figure: {value(st['datasetKey'], st['series'], st['x'])}, {resolve(st.get('label', ''))}")
        for g in s.get("groups") or []:
            for it in g["items"]:
                text, cue = (it, None) if isinstance(it, str) else (it.get("text", ""), it.get("cue"))
                out.append(f"▸ {g['tag']}: {resolve(text)}" + (f" (on “{cue}”)" if cue else " ⏱"))
        for b in s.get("bullets", []):
            if isinstance(b, str):
                out.append(f"▸ {resolve(b)} ⏱")
            elif "zoom" in b:
                out.append(f"🔍 {b['zoom']}" + (f" (on “{b['cue']}”)" if b.get("cue") else " ⏱"))
            else:
                out.append(f"▸ {resolve(b['text'])}" + (f" (on “{b['cue']}”)" if b.get("cue") else " ⏱"))
        if s.get("chart"):
            out.append(f"▸ Chart: {s['chart']['datasetKey']}" + (f" (on “{s['chartCue']}”)" if s.get("chartCue") else ""))
    total = sum(words.values())
    out += ["", "---", "", "## Length", "", "| Speaker | Spoken words (figures ≈ 5) | At 150 words a minute |", "|---|---:|---|"]
    for k, w in words.items():
        out.append(f"| {k} | {w} | {w / 150:.1f} min |")
    out.append(f"| **All** | **{total}** | **{total / 150:.1f} min**, plus about 30 s of transitions and section cards |")
    (ROOT / "docs/script/pitch-script-v10.md").write_text("\n".join(out) + "\n")
    print(f"pitch-script-v10.md: {len(slides)} slides, {total} words")


if __name__ == "__main__":
    main()
